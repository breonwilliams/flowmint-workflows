#!/usr/bin/env bash
#
# Phase 1 smoke test for v0.6.0 scheduled triggers.
#
# Two passes:
#   1. PHP syntax check (php -l) on every file modified in Phase 1.
#   2. Functional smoke test via wp-cli (loads WP, runs migrations,
#      exercises validator + repository + hooks).
#
# Run from Local by Flywheel's "Open Site Shell":
#   cd "/Users/breonwilliams/Local Sites/ai-section-builder/app/public/wp-content/plugins/flowmint-workflows"
#   bash bin/smoke-test-phase1.sh
#
# Exit code: number of failures across both passes (0 = clean).

set -u

PLUGIN_DIR="$( cd "$( dirname "${BASH_SOURCE[0]}" )/.." && pwd )"
cd "$PLUGIN_DIR" || exit 99

echo
echo "================================================"
echo " FlowMint Workflows v0.6.0 — Phase 1 Smoke Test"
echo "================================================"
echo
echo "Plugin dir: $PLUGIN_DIR"
echo

# -----------------------------------------------------------------
# Pass 1: php -l on every modified file
# -----------------------------------------------------------------
echo "------------------------------------------------"
echo " Pass 1 / 2 — PHP syntax check (php -l)"
echo "------------------------------------------------"

FILES=(
  "flowmint-workflows.php"
  "includes/class-fmw-autoloader.php"
  "includes/Database/class-fmw-schema.php"
  "includes/Database/class-fmw-workflow-repository.php"
  "includes/Core/class-fmw-workflow.php"
  "includes/Core/class-fmw-workflow-validator.php"
  "includes/Core/class-fmw-schedule-listener.php"
  "includes/Connectors/REST/class-fmw-rest-workflows.php"
  "includes/Connectors/REST/class-fmw-rest-preflight.php"
  "bin/smoke-test-phase1.php"
)

LINT_FAILS=0
for f in "${FILES[@]}"; do
  if [[ ! -f "$f" ]]; then
    echo "  MISSING  $f"
    LINT_FAILS=$((LINT_FAILS + 1))
    continue
  fi

  OUTPUT=$( php -l "$f" 2>&1 )
  if [[ "$OUTPUT" == *"No syntax errors"* ]]; then
    echo "  OK       $f"
  else
    echo "  FAIL     $f"
    echo "$OUTPUT" | sed 's/^/             /'
    LINT_FAILS=$((LINT_FAILS + 1))
  fi
done

echo
echo "Pass 1 result: $LINT_FAILS lint failure(s)."
echo

if [[ $LINT_FAILS -gt 0 ]]; then
  echo "Stopping — fix syntax errors before running the functional test."
  exit $LINT_FAILS
fi

# -----------------------------------------------------------------
# Pass 2: wp eval-file smoke test
# -----------------------------------------------------------------
echo "------------------------------------------------"
echo " Pass 2 / 2 — Functional smoke test (wp-cli)"
echo "------------------------------------------------"
echo

if ! command -v wp >/dev/null 2>&1; then
  echo "  WP-CLI not on PATH. Run this script from Local's site shell"
  echo "  (right-click the site in Local → Open Site Shell)."
  exit 100
fi

# Mark a position in debug.log so we can tail just the new entries
# generated by THIS smoke test run. wc -c gives byte count; we use it
# as a "before" offset.
DEBUG_LOG="$PLUGIN_DIR/../../debug.log"
DEBUG_LOG_BEFORE=0
if [[ -f "$DEBUG_LOG" ]]; then
  DEBUG_LOG_BEFORE=$( wc -c < "$DEBUG_LOG" | tr -d ' ' )
fi

wp eval-file bin/smoke-test-phase1.php
FUNC_FAILS=$?

# If the functional pass failed, dump anything WordPress wrote to its
# debug.log during this run (Xdebug step-debug spam filtered out).
if [[ $FUNC_FAILS -ne 0 && -f "$DEBUG_LOG" ]]; then
  echo
  echo "------------------------------------------------"
  echo " New debug.log entries from this run (Xdebug filtered)"
  echo "------------------------------------------------"
  DEBUG_LOG_AFTER=$( wc -c < "$DEBUG_LOG" | tr -d ' ' )
  if [[ "$DEBUG_LOG_AFTER" -gt "$DEBUG_LOG_BEFORE" ]]; then
    tail -c +$(( DEBUG_LOG_BEFORE + 1 )) "$DEBUG_LOG" \
      | grep -v "Xdebug" \
      | tail -50
  else
    echo "(no new debug.log entries from this run)"
  fi
fi

echo
echo "================================================"
echo " TOTAL: $LINT_FAILS lint failures + $FUNC_FAILS functional failures"
echo "================================================"

exit $(( LINT_FAILS + FUNC_FAILS ))
